def get_intervals(ys_timestamp_dict: dict[str, Video_Timestamps]):
    intervals_dict = {}
    for filename, t in ys_timestamp_dict.items():
        q_bonus_start_time = []
        for idx in range(0, len(t.ling_hua_q), 2):
            sec = damage_to_second[t.ling_hua_q[idx + 1][-1]]
            min_t = round(t.ling_hua_q[idx][0] - t.q_anim_start - sec + 0.001, 3)
            max_t = round(t.ling_hua_q[idx + 1][0] - t.q_anim_start - sec, 3)
            q_bonus_start_time.append((min_t, max_t))

        intervals_dict[filename] = {
            "Q动画开始 - Q出伤": t.q_damage - t.q_anim_start,
            "q增伤开始时间": q_bonus_start_time,
        }
    
    return intervals_dict


def print_func(description, raw_intervals, soreted_valid_intervals:list):
    if description == "Q动画开始 - Q出伤":
        generic_print_func(description, raw_intervals, soreted_valid_intervals)
        return
    
    s = description + ": "

    for filename, raw_interval in raw_intervals:
        s += "[" + filename + ":"
        if isinstance(raw_interval, list):
            # 加上编号，避免太多时数数浪费时间
            s += ", ".join([str(i+1) +":" + str(raw_interval[i]) for i in range(0, len(raw_interval))]) + "]"
        else:
            s += str(raw_interval)
        s += '], '

    s += "\n"
    soreted_valid_intervals.sort(key=lambda x: x[0], reverse=True)
    s += "按下限降序: " + str(soreted_valid_intervals)
    s += "\n"
    soreted_valid_intervals.sort(key=lambda x: x[1])
    s += "按上限升序: " + str(soreted_valid_intervals)
    s += "\n"
    print(s)


