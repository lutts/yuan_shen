class Video_Timestamps(NamedTuple):
    press_e: Ys_Timestamp
    e_hit: Ys_Timestamp
    e_damage: Ys_Timestamp
    first_kou_xue: list[Ys_Timestamp]

def get_intervals(ys_timestamp_dict: dict[str, Video_Timestamps]):
    intervals_dict = {}
    for filename, t in ys_timestamp_dict.items():
        intervals_dict[filename] = {
            "点按e - 命中": t.e_hit - t.press_e,
            "命中 - 出伤": t.e_damage - t.e_hit,
            "点按e - 首次扣血": t.first_kou_xue[0] - t.press_e,
            "命中 - 首次扣血": t.first_kou_xue[0] - t.e_hit,
            "三小只首次扣血范围": t.first_kou_xue[-1] - t.first_kou_xue[0],
        }
    
    return intervals_dict

