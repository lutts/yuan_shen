class Video_Timestamps(NamedTuple):
    heal_times: list[list[Ys_Timestamp]]


def get_intervals(ys_timestamp_dict: dict[str, Video_Timestamps]):
    intervals_dict = {}
    for filename, t in ys_timestamp_dict.items():
        ht_intervals = []
        for ht in t.heal_times:
            ht_intervals.extend([ht[i] - ht[i - 1] for i in range(3, len(ht))])

        intervals_dict[filename] = {
            "阿忍e开始 - 阿忍e治疗": [ht[1] - ht[0] for ht in t.heal_times],
            "阿忍e治疗 - 芙芙首次治疗": [ht[2] - ht[1] for ht in t.heal_times],
            "阿忍e开始 - 芙芙首次治疗": [ht[2] - ht[0] for ht in t.heal_times],
            "芙芙后续治疗间隔": ht_intervals,
        }
    
    return intervals_dict

