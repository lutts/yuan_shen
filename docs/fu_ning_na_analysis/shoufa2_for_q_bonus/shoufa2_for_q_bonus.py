class Video_Timestamps(NamedTuple):
    q_anim_start: Ys_Timestamp
    q_damage: Ys_Timestamp
    pao_pao_disappear: Ys_Timestamp
    last_bonused_hit: Ys_Timestamp
    last_bonused_damage: Ys_Timestamp
    first_unbonused_hit: Ys_Timestamp
    first_unbonused_damage: Ys_Timestamp


def get_intervals(ys_timestamp_dict: dict[str, Video_Timestamps]):
    intervals_dict = {}
    for filename, t in ys_timestamp_dict.items():
        intervals_dict[filename] = {
            "Q动画开始 - 泡泡消失": t.pao_pao_disappear - t.q_anim_start,
            "泡泡消失 - 最后一次增伤命中": t.last_bonused_hit - t.pao_pao_disappear,
            "泡泡消失 - 第一次无增伤命中": t.first_unbonused_hit - t.pao_pao_disappear,
            "Q动画开始 - 最后一次增伤命中": t.last_bonused_hit - t.q_anim_start,

            "Q动画开始 - Q出伤": t.q_damage - t.q_anim_start,
            "沙龙成员命中 - 出伤": [t.last_bonused_damage - t.last_bonused_hit, 
                            t.first_unbonused_damage - t.first_unbonused_hit]
        }
    
    return intervals_dict

